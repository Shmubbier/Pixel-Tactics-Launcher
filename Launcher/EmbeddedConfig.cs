using System;
using System.Text;

namespace PtoLauncher;

// Compiled-in defaults for the Discord app id, its large-image asset key, and the Firebase URL, so a
// shipped bundle works with NO settings.ini and NO firebase.txt on disk (the old plaintext files are
// dev-only overrides; the bundle carries neither).
//
// These are XOR+Base64 OBFUSCATED, not encrypted: the key lives in this same binary, so anyone with a
// decompiler can recover the values. That is unavoidable for a client-side secret. The point is only to
// keep the values out of an editable text file and out of a plain `strings` dump, so a tester can't
// casually point the launcher at their own Firebase or swap the Discord app by editing a config. None of
// these values is actually sensitive (a Firebase DB URL and a Discord app id are both semi-public); the
// real anti-tamper story is server-side validation, not this.
static class EmbeddedConfig
{
    static readonly byte[] K = Encoding.ASCII.GetBytes("PtoC151!SteamP2P");

    // Generated by Base64(XOR(utf8(value), K)). To change a value, re-run the same transform (see the
    // launcher build notes) and paste the new blob here.
    const string FirebaseB64 = "OAAbM0IPHg4jAApMHWJCfTQRCSJEWUUMIQABA0MxQTkxWRwsREFZRDIHEVBDNlsiNRYOMFRRUFUyFgQSCH5TICBb";
    const string AppIdB64    = "YUFadwIABhRjRFFZXmAFZmFAWQ==";
    const string LargeKeyB64 = "PBsILA==";

    public static string FirebaseUrl => Decode(FirebaseB64);
    public static string DiscordAppId => Decode(AppIdB64);
    public static string DiscordLargeKey => Decode(LargeKeyB64);

    static string Decode(string b64)
    {
        try
        {
            var x = Convert.FromBase64String(b64);
            for (int i = 0; i < x.Length; i++) x[i] ^= K[i % K.Length];
            return Encoding.UTF8.GetString(x);
        }
        catch { return ""; }
    }
}
